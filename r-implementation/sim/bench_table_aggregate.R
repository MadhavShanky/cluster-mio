# bench_table_aggregate.R -- combine the per-cell shards written by sim/bench_table.R into the final
# benchmark CSV + LaTeX table. Run after all shard_*.csv exist (or sourced by bench_table.R in a full run).
# Idempotent: re-reads whatever shards are present.
if (!nzchar(getOption("scs.bench.aggregating", ""))) {  # allow standalone Rscript invocation
  if (!exists("setwd_done")) suppressWarnings(setwd(Sys.getenv("MIO_DIR", "C:/Users/tomch/AIProjects/research/MIO LMM")))
}
dir <- "sim/results_bench"
files <- list.files(dir, pattern = "^shard_[0-9]+_[0-9]+\\.csv$", full.names = TRUE)
if (!length(files)) stop("no shard_*.csv in ", dir, " -- run sim/bench_table.R (or its array) first")
res <- do.call(rbind, lapply(files, read.csv, stringsAsFactors = FALSE))
res <- res[order(res$gi, res$rep), ]
write.csv(res, file.path(dir, "bench_table.csv"), row.names = FALSE)
cat(sprintf("aggregated %d shards -> %s/bench_table.csv (%d rows; K: %s)\n",
            length(files), dir, nrow(res), paste(sort(unique(res$K)), collapse = ",")))

med <- function(v) if (all(is.na(v))) NA_real_ else stats::median(v, na.rm = TRUE)
B_STAB <- if (isTRUE(as.logical(Sys.getenv("SIM_QUICK", "FALSE")))) 10L else 50L
agg <- do.call(rbind, by(res, res$K, function(s) data.frame(
  K = s$K[1], lambda = s$lambda[1], reps = nrow(s),
  single = med(s$t_single), cvpath = med(s$t_cvpath), stab = med(s$t_stab),
  lmm = med(s$t_lmm), glasso = med(s$t_glasso), l0learn = med(s$t_l0learn),
  scs_opt = all(abs(s$gap_scs_brute[is.finite(s$gap_scs_brute)]) < 1e-8))))
agg <- agg[order(agg$K), ]
REPS_TOT <- max(agg$reps)
fmt <- function(x) ifelse(is.na(x), "---", formatC(x, format = "f", digits = ifelse(x < 1, 3, 2)))
rows <- apply(agg, 1, function(r) sprintf("%s & %s & %s & %s & %s & %s & %s & %s \\\\",
  r["K"], r["lambda"], fmt(as.numeric(r["single"])), fmt(as.numeric(r["cvpath"])), fmt(as.numeric(r["stab"])),
  fmt(as.numeric(r["lmm"])), fmt(as.numeric(r["glasso"])), fmt(as.numeric(r["l0learn"]))))
tex <- c(
  "% auto-generated by sim/bench_table_aggregate.R -- median wall-clock seconds, identical (p=5, n_k=30) instances",
  "\\begin{table}[ht]\\centering",
  sprintf("\\caption{Benchmark under identical conditions ($p=5$, $n_k=30$, sparse $\\pi=0.05$, $\\delta=2$; median seconds over %d replicates). SCS columns: a single fit, the cross-validated budget path, and the $B=%d$ stability layer. Competitors: the Gaussian mixed model (\\texttt{lme4} REML), group lasso (\\texttt{cv.glmnet}), and the open-source L0 solver \\citep{hazimeh2020fast} at matched cardinality. SCS returned the brute-force optimum on every enumerable instance.}", REPS_TOT, B_STAB),
  "\\label{tab:bench}\\small\\begin{tabular}{rrcccccc}", "\\toprule",
  "$K$ & $\\lambda$ & SCS fit & SCS CV path & SCS stability & lme4 & group lasso & L0Learn \\\\", "\\midrule",
  rows, "\\bottomrule", "\\end{tabular}\\end{table}")
writeLines(tex, file.path(dir, "bench_table.tex"))
cat("wrote", file.path(dir, "bench_table.tex"), "\n"); print(agg, row.names = FALSE)
