# flagged_table.R -- actionable flagged-hospital table (ref2 item Q, enhancement).
# Post-processing only (no refit): reads the saved fits + inference. For each hospital on the stability
# watch-list (selection freq >= 0.8, matching the manuscript), reports n_k, direction, selection frequency,
# the unshrunk SCS effect (and its multiplicative LOS reading), the BLUP, and the risk-adjustment
# sensitivity status (core = flagged under every spec in {tx_,real}data_sensitivity.R; else borderline).
# Outputs data/flagged_hospitals_{NY,TX}.csv (real ids) + flagged_hospitals.tex (anonymized index).
suppressWarnings(suppressMessages({ setwd(Sys.getenv("MIO_DIR", "C:/Users/tomch/AIProjects/research/MIO LMM")) }))
PI_THR <- 0.8
I <- readRDS("data/inference_both.rds")

build <- function(inf, result_rds, flags_rds, prefix) {
  R <- readRDS(result_rds); nk <- table(as.character(R$fit$data$cluster))
  fr <- inf$stability$freq; watch <- names(fr)[fr >= PI_THR]
  if (!length(watch)) return(NULL)
  g0 <- inf$g0[watch]; bl <- inf$blup[watch]
  core <- character(0)
  if (file.exists(flags_rds)) { fl <- readRDS(flags_rds); core <- Reduce(intersect, fl) }
  sens <- ifelse(watch %in% core, "core", ifelse(file.exists(flags_rds), "borderline", "n.a."))
  df <- data.frame(id = watch, n_k = as.integer(nk[watch]),
                   direction = ifelse(g0 > 0, "longer", "shorter"),
                   pi_hat = round(as.numeric(fr[watch]), 2),
                   gamma_hat = round(as.numeric(g0), 3),
                   pct_LOS = round(100 * (exp(as.numeric(g0)) - 1), 1),
                   blup = round(as.numeric(bl), 3), sensitivity = sens,
                   stringsAsFactors = FALSE)
  df <- df[order(-abs(df$gamma_hat)), ]
  df$idx <- sprintf("%s%02d", prefix, seq_len(nrow(df)))
  df
}
ny <- build(I$sparcs, "data/sparcs/hf_scs_result.rds", "data/sparcs/sensitivity_flags.rds", "NY")
tx <- build(I$tx,     "data/tx/tx_hf_scs_result.rds",  "data/tx/sensitivity_flags.rds",     "TX")
if (!is.null(ny)) write.csv(ny, "data/flagged_hospitals_NY.csv", row.names = FALSE)
if (!is.null(tx)) write.csv(tx, "data/flagged_hospitals_TX.csv", row.names = FALSE)

## anonymized LaTeX table (no facility ids) --------------------------------------------------------
texrows <- function(df, state) if (is.null(df)) character(0) else
  c(sprintf("\\multicolumn{7}{l}{\\emph{%s}}\\\\", state),
    apply(df, 1, function(r) sprintf("%s & %s & %s & %s & %s & %s & %s \\\\",
      r["idx"], r["n_k"], r["direction"], r["pi_hat"], r["gamma_hat"], r["pct_LOS"], r["sensitivity"])))
tex <- c("% auto-generated by flagged_table.R -- stability watch-list (freq >= 0.8)",
  "\\begin{table}[ht]\\centering",
  "\\caption{Stability watch-list of flagged hospitals (selection frequency $\\hat\\pi_k\\ge0.8$). $\\hat\\gamma_k$ is the unshrunk post-selection effect on log length of stay (\\%LOS $\\approx100(e^{\\hat\\gamma_k}-1)$, descriptive, not unbiased); BLUP is the mixed-model shrinkage estimate; sensitivity status is from the risk-adjustment analysis (Supplement~S4). Hospital labels are anonymized.}",
  "\\label{tab:watchlist}\\small\\begin{tabular}{lrlrrrl}", "\\toprule",
  "hospital & $n_k$ & direction & $\\hat\\pi_k$ & $\\hat\\gamma_k$ & \\%LOS & sensitivity \\\\", "\\midrule",
  texrows(ny, "New York SPARCS"), "\\midrule", texrows(tx, "Texas PUDF"),
  "\\bottomrule", "\\end{tabular}\\end{table}")
writeLines(tex, "flagged_hospitals.tex")
cat(sprintf("saved data/flagged_hospitals_{NY,TX}.csv + flagged_hospitals.tex (NY %d, TX %d at pi>=%.1f)\n",
            if (is.null(ny)) 0 else nrow(ny), if (is.null(tx)) 0 else nrow(tx), PI_THR))
